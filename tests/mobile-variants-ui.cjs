const assert = require('node:assert/strict')
const { chromium } = require('@playwright/test')
async function main() {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
  const context = await browser.newContext({ viewport: {width:390,height:844}, isMobile:true, hasTouch:true })
  const page = await context.newPage()
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  try {
    await page.goto(process.env.TEST_URL || 'http://127.0.0.1:4173/qwerty-learner/#/gallery')
    await page.getByRole('button',{name:'下一页'}).click()
    await page.getByRole('button',{name:'开始使用'}).click()
    await page.locator('input[aria-label="选择 JSON 辞书"]').setInputFiles({name:'variants.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify([{name:'catalog',trans:['目录'],spellings:['catalogue']},{name:'unhelpful',segments:['un','help','ful'],trans:['无帮助的']}]))})
    await page.getByText('variants',{exact:true}).waitFor()
    await page.getByTestId('dictionary-card').getByText('variants',{exact:true}).click()
    await page.getByRole('button',{name:'继续学习新词',exact:true}).click()
    await page.getByTestId('spelling-word').waitFor()
    const input=page.getByRole('textbox',{name:'输入单词拼写'})
    await input.tap()
    await page.getByRole('button',{name:'提交',exact:true}).waitFor()
    await input.pressSequentially('catalogx',{delay:80})
    await input.press('Backspace')
    await input.pressSequentially('ue',{delay:80})
    await page.getByRole('button',{name:'提交',exact:true}).tap()
    await page.waitForFunction(()=>document.querySelector('[data-testid="spelling-word"]')?.getAttribute('data-word')==='unhelpful')
    await page.getByRole('button',{name:/Easy/}).waitFor()
    const link=page.locator('a[href^="https://chatgpt.com/?q="]')
    await link.waitFor()
    assert.match(await link.getAttribute('href'),/unhelpful/)
    assert.deepEqual(errors,[])
    console.log('mobile forced whole-word variant, backspace, zero-error rating and imported segmentation: pass')
  } finally {await browser.close()}
}
main().catch(e=>{console.error(e);process.exitCode=1})
